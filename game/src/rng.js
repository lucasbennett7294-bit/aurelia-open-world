// Deterministic RNG shared by the driving, traffic and pedestrian systems.
// One job: hand out seeded random functions so the city plays the same
// way on every load. No unseeded Math.random anywhere in game code.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function random() {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
